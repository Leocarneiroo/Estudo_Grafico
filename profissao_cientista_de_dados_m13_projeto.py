"""Existe uma variaçao muito grande de preço nesta categoria de produtos, a distribuição apresenta muitos outliers com preços muito acima da maioria.

# 4 - Plote um gráfico de barras onde temos a média de descontos por categoria.
"""

# Seu código aqui
media_desconto_por_categoria = df.groupby('Categoria')['Desconto'].mean().reset_index()
print(media_desconto_por_categoria)

fig = px.bar(media_desconto_por_categoria, x='Categoria', y='Desconto', orientation='v', title='Media de Descontos', labels={'Descontos'})
fig.show()

"""# 5 - Plote um gráfico de mapa interativo agrupando os dados por categoria, marca e trazendo a média de desconto."""

# Seu código aqui
categoria_marca = df.groupby(['Categoria', 'Marca'])['Desconto'].mean().reset_index()
print(categoria_marca)

fig = px.treemap(categoria_marca,
                 path=['Categoria', 'Marca'], values='Desconto',
                 title='Desconto por marca e categoria',
                 color='Categoria')
fig.show()